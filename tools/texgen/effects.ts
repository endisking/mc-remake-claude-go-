function badge(t: Tex, x0: number, y0: number, color: number, glyph: string[]): void {
  const base: RGBA = [(color >> 16) & 255, (color >> 8) & 255, color & 255, 255];
  const rim = shade(base, 0.55), hi = mix(base, hex('#ffffff'), 0.45);
  const cx = 8.5, cy = 8.5;
  for (let y = 0; y < 18; y++)
    for (let x = 0; x < 18; x++) {
      const d = Math.hypot(x - cx, y - cy);
      if (d > 8.4) continue;
      let c: RGBA = base;
      if (d > 7.2) c = rim;
      else if (x + y < 12 && d > 4.5) c = hi;
      else if (x + y > 22) c = shade(base, 0.8);
      t.set(x0 + x, y0 + y, c);
    }
  // glyph: light, with a dark drop shadow so it reads on pale colours
  const light = mix(hex('#ffffff'), base, 0.12), dark = shade(base, 0.35);
  glyph.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) if (row[i] === '#') t.set(x0 + 5 + i, y0 + 5 + j, dark);
  });
  glyph.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) if (row[i] === '#') t.set(x0 + 4 + i, y0 + 4 + j, light);
  });
}

function frame(t: Tex, x0: number, y0: number, ambient: boolean): void {
  const out = hex('#000000'), lt = hex(ambient ? '#d8c58c' : '#ffffff'), bg = hex(ambient ? '#a8955c' : '#c6c6c6'), sh = hex(ambient ? '#6b5a2c' : '#555555');
  for (let y = 0; y < 24; y++)
    for (let x = 0; x < 24; x++) {
      const corner = (x === 0 || x === 23) && (y === 0 || y === 23);
      if (corner) continue;
      let c = bg;
      if (x === 0 || y === 0 || x === 23 || y === 23) c = out;
      else if (x === 1 || y === 1) c = lt;
      else if (x === 22 || y === 22) c = sh;
      t.set(x0 + x, y0 + y, c);
    }
}

/** 8 × 4 icons (index = effect id − 1) at 18 px, then the two 24 px frames at y = 72. */
export function mobEffects(): Tex {
  const t = new Tex(144, 96);
  for (let id = 1; id <= 32; id++) {
    const i = id - 1;
    badge(t, (i % 8) * 18, Math.floor(i / 8) * 18, EFFECT_COLORS[id]!, G[id]!);
  }
  frame(t, 0, 72, false);
  frame(t, 24, 72, true);
  return t;
}
